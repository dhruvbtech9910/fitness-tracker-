package com.fitnesstracker;

import com.fitnesstracker.dao.*;
import com.fitnesstracker.dto.AuthRequest;
import com.fitnesstracker.dto.AuthResponse;
import com.fitnesstracker.dto.RegisterRequest;
import com.fitnesstracker.entity.FitnessGoal;
import com.fitnesstracker.entity.Progress;
import com.fitnesstracker.entity.User;
import com.fitnesstracker.entity.Workout;
import com.fitnesstracker.entity.WorkoutExercise;
import com.fitnesstracker.jdbc.DatabaseConnection;
import com.fitnesstracker.service.AuthService;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.ActiveProfiles;

import java.sql.Connection;
import java.sql.SQLException;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest
@ActiveProfiles("dev")
public class JdbcIntegrationTest {

    @Autowired
    private UserDao userDao;

    @Autowired
    private WorkoutDao workoutDao;

    @Autowired
    private GoalDao goalDao;

    @Autowired
    private ProgressDao progressDao;

    @Autowired
    private ChallengeDao challengeDao;

    @Autowired
    private AuthService authService;

    @Test
    @DisplayName("Verify JDBC Connection can be obtained and is valid")
    void testJdbcConnection() throws SQLException {
        try (Connection conn = DatabaseConnection.getConnection()) {
            assertNotNull(conn, "JDBC Connection should not be null");
            assertFalse(conn.isClosed(), "JDBC Connection should be open");
            assertTrue(conn.isValid(2), "JDBC Connection should respond to ping within 2 seconds");
        }
    }

    @Test
    @DisplayName("Verify User Registration and Login via JDBC & BCrypt")
    void testUserRegistrationAndLogin() {
        String testEmail = "jdbc_test_" + System.currentTimeMillis() + "@fitpulse.pro";

        RegisterRequest regReq = new RegisterRequest();
        regReq.setName("JDBC Test Athlete");
        regReq.setEmail(testEmail);
        regReq.setPassword("Password123!");
        regReq.setFitnessGoal("Hypertrophy");
        regReq.setActivityLevel("Very Active");

        // 1. Register User via JDBC
        AuthResponse regResp = authService.register(regReq);
        assertNotNull(regResp, "Registration response must not be null");
        assertNotNull(regResp.getToken(), "JWT token should be returned");
        assertEquals(testEmail, regResp.getUser().getEmail());

        // 2. Read back User via JDBC UserDao
        Optional<User> fetched = userDao.findByEmail(testEmail);
        assertTrue(fetched.isPresent(), "User should be found in database via JDBC");
        assertEquals("JDBC Test Athlete", fetched.get().getName());

        // 3. Login User via JDBC AuthService
        AuthRequest loginReq = new AuthRequest(testEmail, "Password123!");
        AuthResponse loginResp = authService.login(loginReq);
        assertNotNull(loginResp, "Login response must not be null");
        assertNotNull(loginResp.getToken(), "JWT token should be generated on login");
        assertEquals(testEmail, loginResp.getUser().getEmail());
    }

    @Test
    @DisplayName("Verify Workout CRUD with Exercises inside JDBC Transactions")
    void testWorkoutCrudWithTransaction() {
        // Create Workout object with exercises
        Workout workout = new Workout();
        workout.setTitle("Bench Press Overload");
        workout.setCategory("Strength");
        workout.setDuration("45 Min");
        workout.setDurationMinutes(45);
        workout.setCalories("420 kcal");
        workout.setCaloriesBurned(420);
        workout.setDifficulty("Intermediate");
        workout.setTargetMuscles("Chest, Triceps");
        workout.setDate("Today");

        workout.addExercise(new WorkoutExercise("Flat Barbell Bench", 4, 8, 100.0, 15, true));
        workout.addExercise(new WorkoutExercise("Tricep Dips", 3, 12, 0.0, 10, true));

        // 1. Create Workout in JDBC Transaction
        Workout created = workoutDao.create(workout, null);
        assertNotNull(created.getId(), "Workout ID must be generated by database");
        assertTrue(created.getId() > 0);

        // 2. Read Workout back
        Optional<Workout> retrieved = workoutDao.findById(created.getId());
        assertTrue(retrieved.isPresent(), "Workout must be retrieved via JDBC");
        assertEquals("Bench Press Overload", retrieved.get().getTitle());
        assertEquals(2, retrieved.get().getExercises().size(), "Workout should contain 2 exercises");

        // 3. Update Workout
        retrieved.get().setTitle("Heavy Bench Press Overload");
        workoutDao.update(retrieved.get());
        Optional<Workout> updated = workoutDao.findById(created.getId());
        assertTrue(updated.isPresent());
        assertEquals("Heavy Bench Press Overload", updated.get().getTitle());

        // 4. Test Workout Stats aggregation
        Map<String, Object> stats = workoutDao.getWorkoutStats();
        assertNotNull(stats);
        assertTrue((int) stats.get("totalWorkouts") > 0);

        // 5. Delete Workout (removes exercises and workout in transaction)
        boolean deleted = workoutDao.delete(created.getId());
        assertTrue(deleted, "Workout should be deleted");
        assertTrue(workoutDao.findById(created.getId()).isEmpty(), "Deleted workout should not exist");
    }

    @Test
    @DisplayName("Verify Fitness Goals CRUD via JDBC")
    void testGoalCrud() {
        FitnessGoal goal = new FitnessGoal();
        goal.setTitle("Deadlift 200kg Milestone");
        goal.setCategory("Strength");
        goal.setCurrent(180.0);
        goal.setTarget(200.0);
        goal.setUnit("kg");
        goal.setDeadline("Dec 2026");
        goal.calculateProgress();

        // Save
        FitnessGoal saved = goalDao.save(goal, null);
        assertNotNull(saved.getId());

        // Read
        Optional<FitnessGoal> fetched = goalDao.findById(saved.getId());
        assertTrue(fetched.isPresent());
        assertEquals("Deadlift 200kg Milestone", fetched.get().getTitle());
        assertEquals(90, fetched.get().getProgress());

        // Update
        fetched.get().setCurrent(200.0);
        fetched.get().calculateProgress();
        goalDao.update(fetched.get());

        Optional<FitnessGoal> updated = goalDao.findById(saved.getId());
        assertTrue(updated.isPresent());
        assertEquals(100, updated.get().getProgress());
        assertEquals("completed", updated.get().getStatus());

        // Delete
        boolean deleted = goalDao.delete(saved.getId());
        assertTrue(deleted);
    }

    @Test
    @DisplayName("Verify Personal Records (Progress) tracking via JDBC")
    void testProgressTracking() {
        Progress pr = new Progress();
        pr.setExercise("Overhead Strict Press");
        pr.setWeight("80 kg");
        pr.setReps(3);
        pr.setRecordedDate("Today");
        pr.setBadge("Gold");

        Progress saved = progressDao.save(pr, null);
        assertNotNull(saved.getId());

        List<Progress> list = progressDao.findAll();
        assertFalse(list.isEmpty());

        boolean found = list.stream().anyMatch(p -> "Overhead Strict Press".equals(p.getExercise()));
        assertTrue(found);
    }
}
